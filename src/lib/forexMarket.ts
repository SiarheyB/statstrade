/**
 * Часы работы валютного рынка.
 *
 * Форекс не торгуется с вечера пятницы до вечера воскресенья, и это не сбой:
 * свечей за выходные не существует ни у одного источника. Админке это нужно,
 * чтобы не поднимать тревогу «пары не обновляются» каждую субботу.
 *
 * Границы берём по UTC с запасом в сторону «рынок закрыт»: реальное закрытие
 * плавает на час из-за перехода США на летнее время (21:00 UTC летом, 22:00
 * зимой), а открытие — вечер воскресенья. Запас безопасен: в спорный час
 * тревога просто не поднимется, тогда как ложное «всё пропало» каждые
 * выходные обесценивает предупреждение вообще.
 */

/** Закрыт ли валютный рынок в этот момент (UTC). */
export function isForexMarketClosed(nowMs: number): boolean {
  const d = new Date(nowMs);
  const day = d.getUTCDay(); // 0 = воскресенье
  const hour = d.getUTCHours();

  if (day === 6) return true;                 // суббота — целиком
  if (day === 5 && hour >= 21) return true;   // пятница после закрытия
  if (day === 0 && hour < 22) return true;    // воскресенье до открытия
  return false;
}
