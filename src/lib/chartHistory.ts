// Буфер догруженной истории свечей для графиков карты ордеров и форекса.
//
// График держит в памяти два куска: живое окно (последние N свечей, приходят с
// /api/orderflow) и буфер истории — всё, что догружено скроллом влево. Буфер
// ограничен, иначе прокрутка на годы назад складывает в память сотни тысяч
// объектов.
//
// ГРАБЛИ, ради которых появился этот модуль. Обрезка была такой:
//
//   let merged = [...older, ...buffer];
//   merged = merged.slice(merged.length - MAX);   // оставляем ХВОСТ
//
// Догруженные свечи СТАРШЕ уже загруженных, поэтому встают в начало массива —
// а slice оставлял конец, то есть самые новые. Как только буфер набирал предел,
// каждая следующая догрузка выбрасывалась ровно тем вызовом, который её принёс:
// запрос уходил, ответ приходил, курсор уезжал влево, данные терялись. Со
// стороны это выглядело как «история кончилась» на жёсткой дате, хотя в базе
// лежали годы.
//
// Считать предел легко: на 1h живое окно 800 свечей плюс буфер 4000 — это ровно
// 4800 часов, 200 суток. Отсюда и была та самая дата, дальше которой график не
// прокручивался.

export type HistoryCandle = { t: number };

/**
 * Сколько свечей истории держим в памяти.
 *
 * Свеча — это объект из пяти чисел, в V8 около сотни байт. Прежние 4000 (≈0.4 МБ)
 * были осторожны сверх меры и упирались в 200 суток на часовом таймфрейме.
 * 20 000 — это ~2 МБ и по таймфреймам даёт: 5m ≈ 70 суток, 1h ≈ 2.3 года,
 * 4h ≈ 9 лет, 1d — вся история любого инструмента.
 */
export const MAX_HISTORY_CANDLES = 20_000;

/**
 * Присоединить догруженный (более старый) кусок к буферу истории.
 *
 * При переполнении выбрасываются самые НОВЫЕ свечи буфера, а не только что
 * полученные старые: человек смотрит именно туда, куда прокрутил. Живое окно
 * хранится отдельно и не страдает; если прокрутить обратно вправо после очень
 * глубокого ухода влево, между буфером и живым окном будет разрыв — он
 * закроется перезагрузкой страницы или сменой инструмента. На практике до этого
 * не доходит: предел выше глубины, на которую вообще прокручивают.
 */
export function appendOlderHistory<T extends HistoryCandle>(
  older: T[],
  buffer: T[],
  max: number = MAX_HISTORY_CANDLES,
): T[] {
  if (!older.length) return buffer;
  const merged = buffer.length ? [...older, ...buffer] : older.slice();
  // slice(0, max) — с НАЧАЛА, то есть оставляем самые старые. Прежний
  // slice(merged.length - max) оставлял хвост и терял догруженное.
  return merged.length > max ? merged.slice(0, max) : merged;
}
