// Форма свечи и внутренняя структура рынка.
//
// Прежний генератор рисовал один бар одной формулой: тело по GBM, тени —
// случайная доля от тела. Из-за этого все свечи выходили одинаковыми: похожий
// размер, у каждой обе тени, ни накоплений, ни выносов, ни спокойных участков.
// Настоящий график устроен иначе, и здесь воспроизведены три свойства, из
// которых складывается его вид.
//
// 1. КЛАСТЕРИЗАЦИЯ ВОЛАТИЛЬНОСТИ. На реальном рынке спокойное идёт за
//    спокойным, а буйное за буйным: после сильного движения ещё несколько
//    часов трясёт, после затишья затишье продолжается. Это самое устойчивое
//    статистическое свойство финансовых рядов, и описывает его GARCH(1,1):
//    сегодняшняя дисперсия складывается из долгосрочной средней, вчерашнего
//    квадрата доходности и вчерашней дисперсии. Именно отсюда берутся
//    «поджатия» перед движением и затухание после него.
//
// 2. ВНУТРИДНЕВНАЯ СЕЗОННОСТЬ. Активность внутри суток не равномерна:
//    у биржи она U-образная — всплеск на открытии, провал в середине сессии,
//    всплеск на закрытии; у валют пик приходится на пересечение лондонской и
//    нью-йоркской сессий, а азиатская ночь тиха. Без этого час ночи выглядел
//    так же, как час открытия.
//
// 3. ФОРМА ИЗ ПУТИ, А НЕ ИЗ ФОРМУЛЫ. Тени не «дорисовываются» к телу: бар
//    строится как траектория внутри своего интервала, а O/H/L/C снимаются с
//    неё. Оттуда сами собой берутся марубозу без теней, дожи, длинный верхний
//    хвост после выноса — весь тот словарь форм, ради которого свечи и
//    придумали.
import type { Asset, AssetClass } from "@/engine/entities/types";

// ── Кластеризация волатильности (GARCH(1,1)) ──────────────────────────────
//
// Коэффициенты близки к тем, что получаются при оценке на реальных часовых
// рядах: сумма α+β около 0.98 — высокая инерция, из-за которой всплеск
// волатильности затухает не мгновенно, а за сутки-полтора.
export const GARCH_ALPHA = 0.08;
export const GARCH_BETA = 0.9;
/**
 * Потолок множителя к σ. Без него редкий выброс раскручивает дисперсию в
 * бесконечность: замерено — цена улетала на сотни процентов в год.
 */
export const MAX_VOL_MULTIPLIER = 3;
/** Пол: рынок не замирает совсем даже в самое тихое время. */
export const MIN_VOL_MULTIPLIER = 0.25;

export interface VolState {
  /** Условная дисперсия шага, в долях (не в годовом выражении). */
  variance: number;
  /** Надбавка от свежих новостей; затухает с каждым шагом. */
  newsBoost: number;
}

/** Насколько затухает новостная надбавка за один час. */
export const NEWS_VOL_DECAY = 0.72;
/** Во сколько раз новость раздувает волатильность в свой час. */
export const NEWS_VOL_KICK = 1.4;

export function freshVolState(hourlySigma: number): VolState {
  return { variance: hourlySigma * hourlySigma, newsBoost: 0 };
}

/**
 * Следующее состояние волатильности.
 *
 * `lastReturn` — СТАНДАРТИЗОВАННАЯ логарифмическая доходность прошедшего
 * бара, то есть уже поделённая на сезонность, режим рынка и новостную
 * надбавку. Это важно: если кормить GARCH сырой доходностью, час открытия с
 * его полуторным множителем активности каждый день подбрасывал бы дисперсию,
 * она бы не успевала оседать и раскручивалась по кругу. Замерено на прогоне
 * в 3000 баров: без стандартизации годовой снос уезжал за 600%.
 */
export function nextVolState(
  state: VolState,
  lastReturn: number,
  hourlySigma: number,
  newsHit: boolean,
): VolState {
  const longRun = hourlySigma * hourlySigma;
  const omega = longRun * (1 - GARCH_ALPHA - GARCH_BETA);
  const variance = omega + GARCH_ALPHA * lastReturn * lastReturn + GARCH_BETA * state.variance;
  const capped = Math.min(longRun * MAX_VOL_MULTIPLIER ** 2, Math.max(longRun * MIN_VOL_MULTIPLIER ** 2, variance));
  const decayed = state.newsBoost * NEWS_VOL_DECAY;
  return { variance: capped, newsBoost: newsHit ? decayed + NEWS_VOL_KICK : decayed };
}

// ── Внутридневная сезонность ──────────────────────────────────────────────

/**
 * Множитель активности по часу UTC.
 *
 * Биржа: U-образная кривая сессии 14:00–21:00 UTC (9:30–16:00 в Нью-Йорке).
 * Открытие и закрытие — самые активные полчаса дня, середина сессии самая
 * тихая; это видно на любом внутридневном графике акции.
 *
 * Валюты и металлы: пик на пересечении Лондона и Нью-Йорка (12:00–17:00
 * UTC), спад в азиатскую ночь.
 *
 * Крипта: та же форма, но заметно ровнее — рынок работает всегда, и разница
 * между ночью и днём куда меньше.
 */
export function intradayFactor(assetClass: AssetClass, hourUtc: number): number {
  if (assetClass === "stock" || assetClass === "index" || assetClass === "bond") {
    const SESSION: Record<number, number> = { 14: 1.75, 15: 1.2, 16: 0.85, 17: 0.7, 18: 0.8, 19: 1.05, 20: 1.5 };
    return SESSION[hourUtc] ?? 1;
  }
  if (assetClass === "crypto") {
    if (hourUtc >= 12 && hourUtc < 18) return 1.2;
    if (hourUtc >= 0 && hourUtc < 6) return 0.8;
    return 1;
  }
  // Форекс и сырьё.
  if (hourUtc >= 12 && hourUtc < 17) return 1.5;
  if (hourUtc >= 7 && hourUtc < 12) return 1.2;
  if (hourUtc >= 22 || hourUtc < 6) return 0.55;
  return 0.9;
}

// ── Форма бара ────────────────────────────────────────────────────────────

/** Сколько опорных точек внутри часа. Из них снимаются тени бара. */
export const ANCHORS_PER_HOUR = 12;

/**
 * Мост Броуна: n+1 значений, начинается и заканчивается нулём.
 *
 * Мост, а не обычное блуждание, потому что концы бара уже известны — открытие
 * и закрытие, — а форма между ними должна быть случайной, но при этом
 * приходить ровно куда надо.
 */
export function bridgePath(normalAt: (step: number) => number, n: number): number[] {
  const walk: number[] = [0];
  for (let i = 1; i <= n; i++) walk.push(walk[i - 1] + normalAt(i));
  const total = walk[n];
  // Нормируем на √n: без этого разброс внутри бара зависел бы от числа
  // опорных точек, а не от волатильности. У нормированного моста дисперсия в
  // точке t равна t(1−t) — то есть не больше четверти, — и максимальное
  // отклонение середины бара составляет половину σ, как у настоящего
  // броуновского пути внутри интервала.
  const scale = Math.sqrt(n);
  return walk.map((value, i) => (value - (total * i) / n) / scale);
}

export interface ShapedBar {
  open: number;
  high: number;
  low: number;
  close: number;
  /** Путь цены внутри бара — по нему строятся минутки и тики. */
  path: number[];
}

/**
 * Бар по его концам и внутреннему пути.
 *
 * Экстремумы берутся С ПУТИ, а не дорисовываются: поэтому иногда закрытие
 * совпадает с максимумом (марубозу), иногда тело почти отсутствует (дожи), а
 * иногда остаётся длинный хвост после выноса — как на настоящем графике.
 */
export function shapeBar(open: number, close: number, sigma: number, path: number[]): ShapedBar {
  const logOpen = Math.log(open);
  const logClose = Math.log(close);
  const n = path.length - 1;
  const prices = path.map((offset, i) => Math.exp(logOpen + (logClose - logOpen) * (i / n) + sigma * offset));
  return {
    open,
    close,
    high: Math.max(...prices),
    low: Math.min(...prices),
    path: prices,
  };
}

/**
 * Объём бара.
 *
 * Связан с пройденным путём, а не с телом: час, где цена сходила вверх и
 * вернулась, торговался активно, хотя тело у него нулевое. Новость добавляет
 * всплеск — на публикациях объём и правда подскакивает в разы.
 */
export function barVolume(asset: Asset, path: number[], newsBoost: number, activity: number, noise: number): number {
  let travelled = 0;
  for (let i = 1; i < path.length; i++) travelled += Math.abs(path[i] - path[i - 1]);
  const relative = path[0] > 0 ? travelled / path[0] : 0;
  const base = 40 * (1 + relative * 400) * activity * (1 + newsBoost * 0.8);
  return Math.max(1, base * (0.5 + noise));
}
