// Ключ для тиков — то, что можно отдать в браузер вместо сида мира.
//
// ПОЧЕМУ ЭТОТ МОДУЛЬ ВООБЩЕ ЕСТЬ. Живая цена внутри минуты считается в
// браузере (lib/game/useLiveTick.ts), и раньше для этого клиенту отдавался
// сид мира. Но генератор рынка — чистая детерминированная функция, и она же
// едет в браузерный бандл: имея сид, игрок считал не только текущую минуту, а
// ЛЮБОЙ будущий час по любому инструменту. Проверено реплеем: 293 из 300
// последних баров воспроизводились точь-в-точь. Игра, в которой цену завтра
// можно посчитать сегодня, — это не игра.
//
// Ключ решает это так: наружу уходит односторонняя производная от сида и
// НОМЕРА ЧАСА. Внутри минуты он даёт ровно ту же случайность (тику всё равно,
// из какой строки её взяли), а обратно к сиду не ведёт и на соседний час не
// переносится — значит, следующий бар из него не построить.
import { createHash } from "node:crypto";

const MS_HOUR = 3_600_000;

/** Номер часа мира — единица, на которую выдаётся ключ. */
export function tickHourIndex(now: number): number {
  return Math.floor(now / MS_HOUR);
}

/**
 * Ключ на один час. SHA-256 обрезан до 32 символов: для случайности внутри
 * минуты этого с запасом, а короткая строка не раздувает ответ.
 */
export function deriveTickKey(seed: string, hourIndex: number): string {
  return createHash("sha256").update(`${seed}|ticks|${hourIndex}`).digest("hex").slice(0, 32);
}

/** Когда ключ перестанет действовать — по нему клиент понимает, что пора за новым. */
export function tickKeyExpiry(hourIndex: number): number {
  return (hourIndex + 1) * MS_HOUR;
}
