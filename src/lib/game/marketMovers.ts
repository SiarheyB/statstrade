// Крупные игроки, которые реально двигают рынок.
//
// До этого модуля цена была честным генератором, а «трейдеры» вокруг неё —
// зрителями: обычные боты (bots.ts) держат виртуальный счёт и правда торгуют,
// но на цену это никак не влияет — они реагируют на готовую свечу, как и
// игрок. На вопрос «кто вообще двигает рынок» ответа не было.
//
// Три роли (GamePlayer.botRole), три разных механики:
//
//  - ЦЕНТРОБАНК торгует капиталом самого банка (см. GameBank.tradingPool) и
//    ПОЛНОСТЬЮ детерминирован: решение — чистая функция режима рынка
//    (bull/bear/crisis/…), который и так уже одинаково известен серверу и
//    клиенту как факт (см. readRegime). Это позволяет добавить его влияние
//    ПРЯМО в формулу цены (marketGen.nextCandle), не читая ничего из базы
//    внутри генератора и не открывая заново дыру с предсказуемостью сида:
//    вход та же случайность, что и everywhere в игре, выход — тот же режим,
//    который виден в шапке терминала любому игроку.
//  - ХЕДЖ-ФОНД и МАРКЕТМЕЙКЕР торгуют как обычные боты (bots.ts,
//    decideByRules/decideByModel) — недетерминированно, с реальным риском
//    ошибиться, — но их РАЗМЕР достаточен, чтобы agregate-позиция таких
//    ботов заметно сказывалась на цене. Это НЕ пропускается через сид: их
//    решения читаются из базы В МОМЕНТ генерации свечи (marketStore.ts) и
//    передаются в nextCandle тем же способом, что и новости — готовым
//    параметром, а не пересчитываются внутри чистой функции.
//
// Хедж-фонд и маркетмейкер не отличаются МЕХАНИКОЙ решения (одна и та же
// decideByRules) — только ролью для учёта влияния на цену и размером счёта:
// маркетмейкеру ставится противотрендовая манера (см. botPersonas), поэтому
// на общем графике его позиции чаще гасят чужой перекос, чем усиливают его —
// ровно то, чем маркетмейкеры и живут в реальности (спред, а не направление).

import type { MarketRegimeType } from "@/engine/entities/types";

/** Роли крупных игроков — значения поля GamePlayer.botRole. */
export const MARKET_MOVER_ROLES = ["central_bank", "hedge_fund", "market_maker"] as const;
export type MarketMoverRole = (typeof MARKET_MOVER_ROLES)[number];

/** Инструмент, которым торгует центробанк — единственный, флагманский индекс. */
export const CENTRAL_BANK_ASSET_ID = "IDX_BROAD500";

/**
 * Позиция центробанка по режиму рынка: сторона и доля торгового пула.
 *
 * Крен ПРОТИВ режима, а не по нему: центробанк существует именно затем,
 * чтобы сглаживать крайности — поддержать в кризис, остудить перегрев, — а
 * не разгонять то, что рынок делает и без него. В боковике вмешиваться
 * незачем: там нечего сглаживать.
 */
export function centralBankStance(regime: MarketRegimeType): { side: "long" | "short" | "flat"; sharePct: number } {
  switch (regime) {
    case "crisis":
      return { side: "long", sharePct: 45 };
    case "bear":
      return { side: "long", sharePct: 20 };
    case "bull":
      return { side: "short", sharePct: 15 };
    case "high_volatility":
      return { side: "short", sharePct: 10 };
    case "sideways":
    default:
      return { side: "flat", sharePct: 0 };
  }
}

/**
 * Дополнительный снос цены от вмешательства центробанка — прибавляется к
 * μ ТОЛЬКО у CENTRAL_BANK_ASSET_ID, поверх обычного regime.driftModifier.
 *
 * Числа заметно меньше самих driftModifier режимов (±0.4..1 против ±1.2..3):
 * центробанк смягчает крайность, а не отменяет её — рынок в кризисе всё
 * равно падает, просто не так резко, как упал бы без вмешательства.
 */
export function centralBankDriftBias(regime: MarketRegimeType): number {
  const stance = centralBankStance(regime);
  if (stance.side === "flat") return 0;
  const magnitude = (stance.sharePct / 45) * 1; // 45% (кризис) — потолок влияния
  return stance.side === "long" ? magnitude : -magnitude;
}

/**
 * Потолок влияния совокупной позиции крупных ботов (хедж-фонд +
 * маркетмейкер) на снос цены — доля от «нормального» годового сноса актива.
 *
 * Без потолка одна огромная сделка одного бота могла бы устроить свечу в
 * сотни процентов. С потолком крупный игрок задаёт заметный, но не абсурдный
 * наклон — как и в реальности, где даже кит торгует ПРОТИВ книги заявок, а
 * не в вакууме.
 */
export const BIG_PLAYER_MAX_DRIFT_BIAS = 1.5;

/**
 * Стартовый капитал хедж-фонда и маркетмейкера (см. bots.ts) — и заодно
 * знаменатель для bigPlayerDriftBias.
 *
 * Знаменатель ФИКСИРОВАННЫЙ, а не «эквити самого крупного бота сейчас»:
 * плавающий знаменатель означал бы, что наклон цены дёргается от собственных
 * прибылей/убытков бота, а не только от размера его позиции — лишний
 * источник шума без всякого смысла. Раз задав масштаб, не пересчитываем.
 */
export const BIG_PLAYER_START_EQUITY = 300_000_000;

/**
 * Снос от текущей чистой позиции крупных ботов по инструменту.
 *
 * `netNotional` — сумма (long − short) по номиналу в деньгах (qty × цена
 * входа) среди ботов с ролью hedge_fund/market_maker.
 */
export function bigPlayerDriftBias(netNotional: number): number {
  // Снос растёт пропорционально размеру позиции относительно стартового
  // капитала и упирается в потолок BIG_PLAYER_MAX_DRIFT_BIAS: сложить в один
  // актив весь капитал и ещё немного плечом можно, но дальше рост позиции
  // цену уже не разгоняет сильнее, только удерживает наклон.
  const ratio = netNotional / BIG_PLAYER_START_EQUITY;
  return Math.max(-BIG_PLAYER_MAX_DRIFT_BIAS, Math.min(BIG_PLAYER_MAX_DRIFT_BIAS, ratio));
}

/**
 * Свежесть часа для учёта живой позиции ботов.
 *
 * ensureHistory умеет досчитывать МНОГО пропущенных часов за один вызов
 * (никто не заходил неделю). Текущая позиция ботов — это состояние ИМЕННО
 * сейчас, а не то, каким оно было неделю назад: применять её ко всем
 * досчитываемым часам задним числом значило бы дать хедж-фонду двигать
 * прошлое. Влияние получают только недавние часы — остальные достраиваются
 * так, будто крупных игроков не было (это уже честная генерация сама по
 * себе, просто без их добавки).
 */
export const BIG_PLAYER_RECENT_WINDOW_MS = 3 * 60 * 60 * 1000;
