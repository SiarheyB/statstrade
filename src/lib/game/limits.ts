// Ограничение частоты игровых запросов.
//
// ПОЧЕМУ ОТДЕЛЬНО ОТ lib/ratelimit.ts. Тот считает по IP и защищает вход,
// регистрацию, поддержку — места, где вредитель ещё не представился. В игре
// всё наоборот: заходит человек со своим аккаунтом, и ограничивать надо
// именно ИГРОКА, а не адрес. Иначе двое из одной квартиры мешают друг другу,
// а один злоумышленник обходит счётчик, меняя адрес.
//
// Числа взяты от того, как ходит НАСТОЯЩИЙ клиент (см. store/gameStore.ts):
// котировки раз в 4 с, свечи раз в 15 с, чат раз в 8 с, мир и синхронизация
// раз в 30–60 с. Лимиты выставлены с запасом в несколько раз — чтобы вторая
// открытая вкладка и повторная загрузка страницы никого не задели, — но на
// три порядка ниже того, что нужно скрипту.
import { rateLimit } from "@/lib/ratelimit";

export type GameLimit = "read" | "write" | "sync" | "chat" | "money";

/** Сколько действий за минуту разрешено одному игроку. */
export const GAME_LIMITS: Record<GameLimit, number> = {
  // Чтение рынка: котировки, свечи, мир, лента. Живой клиент даёт ~25/мин.
  read: 240,
  // Обычные изменения: подписки, настройки фонда, публикация сигнала.
  write: 60,
  // Синхронизация профиля. Клиент шлёт раз в минуту; здесь важнее всего:
  // clampSnapshot разрешает рост эквити вчетверо ЗА ВЫЗОВ, и без лимита
  // двадцать вызовов подряд давали 4^20.
  sync: 10,
  // Сообщения в чат: пауза между ними и так три секунды.
  chat: 30,
  // Всё, что двигает деньги между игроками: займы, вклады, выплаты, комиссия
  // ведущему, сделки с банком. Здесь скорость не нужна никому, кроме скрипта.
  money: 30,
};

const WINDOW_MS = 60_000;

/**
 * Разрешено ли действие. Ключ — игрок и вид действия, окно — минута.
 *
 * Возвращает `null`, когда можно, и число секунд до следующей попытки, когда
 * нельзя: маршруту остаётся отдать 429 с этим числом.
 */
export function checkGameLimit(playerKey: string, kind: GameLimit): number | null {
  const result = rateLimit(`game:${kind}:${playerKey}`, GAME_LIMITS[kind], WINDOW_MS);
  return result.ok ? null : result.retryAfterSec;
}
