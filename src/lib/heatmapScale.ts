/**
 * Масштаб яркости карты лимиток.
 *
 * Карта рисует ячейку как долю от масштаба, а ползунок «минимальный размер»
 * гасит всё, что этой доли не набрало. Пока масштабом служил максимум всего
 * загруженного окна, картинку задавала одна самая крупная стена: на 4h окно —
 * 133 дня, и рекорд за это время в разы больше обычного дня. Стены живут там,
 * где цена подолгу стоит; периоды быстрого движения размазаны по ценам, их
 * ячейки на порядок мельче — и уходили в чёрное целиком. Человек видел
 * плотный блок за последние дни и пустоту слева, хотя данные лежали в базе.
 *
 * Поэтому масштаб — перцентиль, и считается по ВИДИМОЙ части карты: прокрутил
 * в сторону — карта подстроилась под этот участок. Так же ведут себя терминалы
 * с картой ликвидности.
 */

/** Доля ячеек, которая упирается в потолок яркости: верхние 10%. */
const QUANTILE = 0.9;
/**
 * Насколько масштаб может быть меньше самой крупной ячейки. Без ограничения
 * выборка из нескольких почти нулевых значений давала ничтожный масштаб — и
 * карта превращалась в сплошную засветку.
 */
const MIN_RATIO_TO_MAX = 1 / 50;

/** Перцентиль набора + защита от вырождения. */
function scaleOf(values: number[]): number {
  if (values.length === 0) return 0;
  values.sort((a, b) => a - b);
  const q = values[Math.min(values.length - 1, Math.floor(values.length * QUANTILE))];
  return Math.max(q, values[values.length - 1] * MIN_RATIO_TO_MAX);
}

/**
 * Масштаб на всю сетку — им отвечает сервер, а клиент берёт его, пока не знает
 * видимого окна (первый кадр) и для старых ответов из кэша.
 *
 * Перцентиль берётся 90-й, а не 99-й: коллектор пишет только КРУПНЫЕ лимитки,
 * непустых ячеек в сетке сотня-другая на 240×110, и 99-й перцентиль такой
 * выборки совпадает с максимумом — то есть не меняет ровно ничего (замер на
 * живых данных: порог проходили те же 15 ячеек, по 90-му — 27).
 */
export function heatmapScale(grid: number[][], maxVal: number): number {
  const values: number[] = [];
  for (const col of grid) for (const v of col) if (v > 0) values.push(v);
  return scaleOf(values) || maxVal;
}

/** Сетка карты в том виде, в каком масштаб её читает. */
export type ScaleSource = {
  grid: number[][];
  cols: number;
  /** Центры колонок: равномерная сетка времени. */
  times: number[];
};

/**
 * Масштаб по видимому диапазону времени — по всем слоям сразу (живое окно и
 * догруженные куски истории), иначе соседние участки карты светились бы
 * по-разному.
 */
export function visibleScale(sources: ScaleSource[], t0: number, t1: number): number {
  const values: number[] = [];
  for (const src of sources) {
    if (!src.cols || src.times.length < 2) continue;
    const step = src.times[1] - src.times[0] || 1;
    const from = Math.max(0, Math.floor((t0 - src.times[0]) / step));
    const to = Math.min(src.cols - 1, Math.ceil((t1 - src.times[0]) / step));
    for (let c = from; c <= to; c++) {
      const col = src.grid[c];
      if (!col) continue;
      for (const v of col) if (v > 0) values.push(v);
    }
  }
  return scaleOf(values);
}
