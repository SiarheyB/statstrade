import { describe, it, expect } from "vitest";
import { mentionsMe } from "@/components/game/ChatPanel";

// Раньше обращение к игроку в чате ничем не отличалось от остального
// текста — заметить, что ответили именно тебе, можно было, только вчитавшись
// в каждую строку. mentionsMe — та же проверка по нику, что сервер уже
// использует для выбора отвечающего бота (см. answerQuestion в bots.ts),
// здесь она нужна для подсветки строки в интерфейсе.
describe("mentionsMe", () => {
  it("находит ник как отдельное слово, без учёта регистра", () => {
    expect(mentionsMe("Гоша, что думаешь про BTC?", "Гоша")).toBe(true);
    expect(mentionsMe("ГОША, ты прав", "Гоша")).toBe(true);
  });

  it("не срабатывает на ник как часть другого слова", () => {
    expect(mentionsMe("Гошария сегодня в плюсе", "Гоша")).toBe(false);
  });

  it("не срабатывает, если ника нет в тексте вовсе", () => {
    expect(mentionsMe("Кто-нибудь смотрит на ETH?", "Гоша")).toBe(false);
  });

  it("пустой ник никогда не считается упоминанием", () => {
    expect(mentionsMe("Привет всем", "")).toBe(false);
  });

  it("ник со спецсимволами регулярки не ломает поиск", () => {
    expect(mentionsMe("C++ Trader, го в лонг", "C++ Trader")).toBe(true);
  });
});
