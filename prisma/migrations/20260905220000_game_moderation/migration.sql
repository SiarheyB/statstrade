-- Модерация чата.
--
-- Админка видела статистику мира, но сделать с ним ничего не могла: ни снять
-- сообщение, ни закрыть рот тому, кто мешает остальным. Общий чат без этого
-- держится ровно до первого желающего его сломать.
--
-- Мут со сроком, а не флагом «забанен»: почти всё, что происходит в чате,
-- лечится паузой, а вечная блокировка требует потом ручного снятия, про
-- которое все забывают.
ALTER TABLE "GamePlayer" ADD COLUMN "mutedUntil" TIMESTAMP(3);

-- Снятое сообщение не удаляем: пропавшая реплика выглядит как сбой, и
-- разобраться, за что человека наказали, потом нечем.
ALTER TABLE "GameChatMessage" ADD COLUMN "removedAt" TIMESTAMP(3);
