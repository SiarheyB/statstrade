-- Срок жизни менторской ссылки. NULL — бессрочная (так вели себя все ссылки до
-- этой колонки, поэтому старые записи трогать не нужно).
--
-- Храним момент истечения, а не «сколько дать»: проверка на странице — это одно
-- сравнение с now(), и срок не «продлевается» сам собой при каждом открытии.
ALTER TABLE "ShareLink" ADD COLUMN "expiresAt" TIMESTAMP(3);

-- Открытие ссылки ищет её по токену и сразу смотрит на срок.
CREATE INDEX "ShareLink_expiresAt_idx" ON "ShareLink"("expiresAt");
