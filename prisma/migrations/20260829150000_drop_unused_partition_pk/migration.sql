-- Снять первичные ключи (id, t) с партиционированных таблиц карты ордеров.
--
-- Схема Prisma про эти таблицы говорит прямым текстом:
--
--   «в БД таблица партиционирована по дням … и НЕ имеет PK — @id здесь только
--    для типизации клиента Prisma»
--
-- Фактически PK был на каждой партиции, и ни одна из них им не пользовалась:
-- idx_scan = 0 ПО ВСЕМ партициям без единого исключения. По id эти таблицы не
-- читает никто — проверено:
--   * через модель Prisma к ним обращается ровно одно место
--     (computeBigTrades в lib/orderflow.ts) и с явным select без id;
--   * всё остальное — сырой SQL по (symbol, exchange, t);
--   * ON CONFLICT на них не используется, то есть для вставок PK не нужен.
--
-- Замер на локальной базе: неиспользуемые PK весили 9016 кБ при 25 МБ данных
-- в этих таблицах. Это ~21% их суммарного объёма — и, что важнее, индексная
-- запись в КАЖДУЮ вставку на самом горячем пути записи в системе (стакан,
-- лента и футпринт пишутся каждые SNAPSHOT_MS по всем фидам).
--
-- Колонку id и её sequence НЕ трогаем намеренно. Выигрыш от них мал (8 байт на
-- строку против 24+ у индексной записи), а цена ошибки велика: Prisma читает
-- модель с обязательным BigInt @id, и NULL в этой колонке сломал бы любое
-- будущее чтение без явного select. Убрать их — отдельное решение, требующее
-- смены модели.
--
-- Новые партиции создаются как PARTITION OF и наследуют структуру родителя,
-- поэтому после снятия PK у родителя они его и не получат
-- (ob_ensure_partitions делает CREATE TABLE ... PARTITION OF, ничего больше).

ALTER TABLE "ObSnapshot"  DROP CONSTRAINT IF EXISTS "ObSnapshot_pkey";
ALTER TABLE "ObTrade"     DROP CONSTRAINT IF EXISTS "ObTrade_pkey";
ALTER TABLE "ObFootprint" DROP CONSTRAINT IF EXISTS "ObFootprint_pkey";
ALTER TABLE "ObBigTrade"  DROP CONSTRAINT IF EXISTS "ObBigTrade_pkey";
